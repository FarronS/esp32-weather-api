#pragma once

#include <Arduino.h>

// ===========================================================================
//  Экран устройства: OLED SSD1306/SSD1315, 128x64, I2C (адрес 0x3C).
//
//  Здесь только функции экранов. Всё остальное — в src/display.cpp:
//  там подробно описано, как рисовать (фреймбуфер), какая разметка
//  на экране, как работают иконки, столбики недели и индикатор "!".
//
//  Текст принимается в UTF-8, кириллица поддерживается.
//  Координата y — ВЕРХ строки текста (не базовая линия).
// ===========================================================================

// Включить экран: питание Vext, Wire, команды панели. Вызывать в setup().
// true  — панель ответила по I2C и готова;
// false — экрана нет: все функции рисования просто ничего не делают.
bool displayInit();

// Две строки по центру экрана (статусы: "WiFi...", "WiFi FAIL", ошибки).
// line2 можно не передавать.
void displayMessage(const char* line1, const char* line2 = "");

// Кадр с часами: крупное время, дата, а под ними — иконка текущей погоды
// и температура на улице.
// hour < 0 — время ещё не получено по NTP: рисуется "--:--" и "синхронизация...".
// cond/tempC — текущая погода из met.no ("Переменная облачность", "+5");
// можно передать nullptr, тогда останется только время и дата.
// stale — true: свежих данных о погоде нет, в углу рисуется "!".
// frame — номер кадра анимации иконки: вызывайте экран периодически
// (например, каждые 180 мс), и солнце будет вращать лучи, дождь — капать,
// снег — падать, молния — мигать. frame = 0 — статичный кадр.
void displayClock(int hour, int minute, int day, int month, int year,
                  const char* cond, const char* tempC, bool stale,
                  uint8_t frame = 0);

// Один столбик недельного графика для displayWeek().
struct WeekDay {
    const char* label;  // число месяца: "17"
    int tmax;           // максимум за день, °C (может быть отрицательным)
};

// Кадр «погода на неделю»: 7 вертикальных столбиков.
// Над столбиком — максимальная температура дня, под ним — число месяца.
// count — сколько дней реально передано (0..7).
// stale — true: свежий прогноз получить не удалось, в углу рисуется "!".
void displayWeek(const WeekDay* days, int count, bool stale);
