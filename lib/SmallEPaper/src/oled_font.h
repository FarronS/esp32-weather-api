static const uint8_t FONT8X8_YO_L[8] = {0x48,0x70,0x48,0xF8,0x40,0x78,0x00,0x00};

// Вернуть указатель на 8 байт символа Unicode (пробел, если не поддерживается).
static inline const uint8_t *font_glyph_cp(uint32_t cp)
{
    if (cp >= 0x20 && cp <= 0x7E)   return FONT8X8[cp - 0x20];
    if (cp >= 0x410 && cp <= 0x42F) return FONT8X8_CYR_U[cp - 0x410];
    if (cp >= 0x430 && cp <= 0x44F) return FONT8X8_CYR_L[cp - 0x430];
    if (cp == 0x401)                return FONT8X8_YO_U;
    if (cp == 0x451)                return FONT8X8_YO_L;
    return FONT8X8[0];              // пробел
}

// Совместимость со старым API: один байт (ASCII).
static inline const uint8_t *font_glyph(char c)
{
    return font_glyph_cp((uint32_t)(unsigned char)c);
}
